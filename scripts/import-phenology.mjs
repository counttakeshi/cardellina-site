/**
 * Turns an eBird frequency export into src/lib/data/phenology.json.
 *
 * "When should I come?" is the most asked question in birding travel and the
 * one this site answers worst, because the honest answer is per species and
 * nobody can hold 136 of those in their head. A bar per month, from real
 * checklist data, answers it for one bird at a glance.
 *
 * Expects a CSV with these columns, in any order:
 *
 *   species_code, common_name, scientific_name, month, frequency, n_checklists
 *
 * month is 1 to 12. frequency is 0 to 1, the proportion of checklists in that
 * month reporting the species. n_checklists is the sample behind it, and is
 * carried through because a frequency of 1.0 from two checklists is not a fact
 * and the chart has to be able to say so.
 *
 * Run: node scripts/import-phenology.mjs <file.csv> [--source "EBD version"]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src', 'lib', 'data', 'phenology.json');

const [file, ...rest] = process.argv.slice(2);
if (!file) {
	console.error('usage: node scripts/import-phenology.mjs <file.csv> [--source "EBD version"]');
	process.exit(1);
}
const sourceFlag = rest.indexOf('--source');
const source = sourceFlag >= 0 ? (rest[sourceFlag + 1] ?? '') : '';

/** Minimal CSV reader: quoted fields, doubled quotes, commas inside quotes. */
function parseCsv(text) {
	const rows = [];
	let row = [];
	let field = '';
	let quoted = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quoted) {
			if (c === '"') {
				if (text[i + 1] === '"') { field += '"'; i++; }
				else quoted = false;
			} else field += c;
			continue;
		}
		if (c === '"') quoted = true;
		else if (c === ',') { row.push(field); field = ''; }
		else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
		else if (c !== '\r') field += c;
	}
	if (field !== '' || row.length) { row.push(field); rows.push(row); }
	return rows.filter((r) => r.some((c) => c.trim() !== ''));
}

const rows = parseCsv(readFileSync(file, 'utf8'));
const header = rows.shift().map((h) => h.trim().toLowerCase());

const need = ['species_code', 'common_name', 'scientific_name', 'month', 'frequency', 'n_checklists'];
const missing = need.filter((n) => !header.includes(n));
if (missing.length) {
	console.error('missing columns: ' + missing.join(', '));
	console.error('found: ' + header.join(', '));
	process.exit(1);
}
const at = (r, name) => r[header.indexOf(name)]?.trim() ?? '';

const byCode = new Map();
let skipped = 0;

for (const r of rows) {
	const code = at(r, 'species_code');
	const month = Number(at(r, 'month'));
	const frequency = Number(at(r, 'frequency'));
	const checklists = Number(at(r, 'n_checklists'));

	if (!code || !Number.isInteger(month) || month < 1 || month > 12) { skipped++; continue; }
	if (!Number.isFinite(frequency) || frequency < 0 || frequency > 1) { skipped++; continue; }

	if (!byCode.has(code)) {
		byCode.set(code, {
			code,
			commonName: at(r, 'common_name'),
			scientificName: at(r, 'scientific_name'),
			monthly: Array(12).fill(0),
			checklists: Array(12).fill(0)
		});
	}
	const entry = byCode.get(code);
	entry.monthly[month - 1] = frequency;
	entry.checklists[month - 1] = Number.isFinite(checklists) ? checklists : 0;
}

const out = {
	_note:
		'Monthly reporting frequency per species in Chiapas. Generated by scripts/import-phenology.mjs. Do not edit by hand.',
	generated: new Date().toISOString().slice(0, 10),
	source,
	region: 'MX-CHP',
	species: [...byCode.values()].sort((a, b) => a.commonName.localeCompare(b.commonName))
};

writeFileSync(OUT, JSON.stringify(out, null, '\t') + '\n');

console.log(`phenology: ${out.species.length} species from ${rows.length} rows`);
if (skipped) console.log(`phenology: ${skipped} rows skipped as unreadable`);
if (!source) console.log('phenology: no --source given. Add the eBird Basic Dataset version so the pages can cite it.');
